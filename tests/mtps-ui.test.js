/* MT PLC Studio UI tests (Playwright, headless Chromium): layouts, resize / rotate, editing, tags, verify, online,
   I/O panel, persistence. Usage: node tests/mtps-ui.test.js */
'use strict';
const path = require('path');
const { chromium } = require('playwright');

const URL = 'file://' + path.resolve(__dirname, '..', 'mtps', 'index.html');
let failed = 0, passed = 0;
function check(name, cond, info = '') {
  if (cond) { passed++; console.log(`  ✓ ${name}`); }
  else { failed++; console.log(`  ✗ ${name} ${info}`); }
}

(async () => {
  const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  // the in-app updater asks the hosted copy for version.json: answer with an older version (no update)
  await ctx.route('https://ronanski.github.io/**', r => r.fulfill({ status: 200, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ version: '0.0.1', build: 'test', notes: '' }) }));
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(URL);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForTimeout(300);
  const ev = (fn, arg) => page.evaluate(fn, arg);
  const S = () => ev(() => { const s = MTPS.App.state; return { layout: s.layout, sel: s.sel, selRung: s.selRung, routine: s.routine, online: s.online, area: s.area }; });
  const rungTexts = () => ev(() => MTPS.App.state.p.tasks[0].programs[0].routines[0].rungs.map(r => r.t));
  const noHScroll = () => ev(() => document.documentElement.scrollWidth <= innerWidth + 1);

  console.log('Start and layouts');
  check('first start: an empty project with one empty rung', (await ev(() => document.title)) === 'MT PLC Studio - New_Project [PLC-CPU 1.0]' && (await rungTexts()).length === 1 && (await rungTexts())[0] === '');
  await ev(() => MTPS.App.openProject(MTPS.App.example()));
  await page.waitForTimeout(100);
  check('the example opens from File > Open', (await ev(() => document.title)) === 'MT PLC Studio - Motor_Demo [PLC-CPU 1.0]');
  check('desktop layout at 1440 × 900', (await S()).layout === 'desktop' && (await page.$('.dmenu')) !== null);
  check('the ladder is drawn (5 rungs and End)', (await page.$$eval('#ladwrap rect.tap[data-rn]', r => r.length)) === 5);
  check('no sideways page scroll on the desktop', await noHScroll());
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 1024, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  check('a narrower window gets the tablet layout', (await S()).layout === 'tablet' && (await page.$('.appbar')) !== null);
  check('tablet: instruction bar with 44 px+ buttons', (await page.$eval('.ibar .gbtn', b => b.getBoundingClientRect().height)) >= 44);
  await page.setViewportSize({ width: 768, height: 1024 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 768, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  check('tablet portrait: organizer becomes a drawer', (await S()).layout === 'tablet' && (await page.$('.org')) === null && (await page.$('[data-drawer="1"]')) !== null);
  check('no sideways page scroll in tablet portrait', await noHScroll());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 390, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  check('phone layout at 390 px: bottom navigation and the + button', (await S()).layout === 'phone' && (await page.$$('.pnav button')).length === 5 && (await page.$('.fab')) !== null);
  check('no sideways page scroll on the phone', await noHScroll());
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 1440, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);

  console.log('Selection survives resize and rotate');
  await ev(() => MTPS.App.select({ ri: 3, path: [0] }));
  await page.setViewportSize({ width: 800, height: 1100 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 800, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  await page.setViewportSize({ width: 1100, height: 800 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 1100, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 390, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);
  const s1 = await S();
  check('rotating and resizing keeps the routine and the selected instruction', s1.routine === 'MainRoutine' && s1.sel && s1.sel.ri === 3 && s1.sel.path[0] === 0);
  check('phone: the selected-instruction bar shows it', (await page.$eval('.selbar', e => e.textContent)).includes('Run_Timer.DN'));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.waitForFunction(w => innerWidth === w && MTPS.App.state.layout === (w < 768 ? 'phone' : w < 1200 ? 'tablet' : 'desktop'), 1440, { timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(80);

  console.log('Editing');
  await ev(() => MTPS.App.select({ ri: 1, path: [0] }));
  await page.click('.gbtn[data-mn="XIO"]');
  await page.waitForTimeout(150);
  check('a toolbar click inserts after the selection and opens the operand editor', (await page.$('#layer .dlg')) !== null && (await rungTexts())[1] === 'XIC(Motor_Run)XIO(?)OTE(Motor_Cmd);');
  await page.fill('#layer [data-op="0"]', 'Fault_Stop');
  await page.waitForTimeout(100);
  check('an unknown name offers New "name"', (await page.$('#layer [data-newtag="Fault_Stop"]')) !== null);
  await page.click('#layer [data-newtag="Fault_Stop"]');
  await page.waitForTimeout(100);
  check('New Tag opens with the name and BOOL for a bit operand', (await page.$eval('#tn', i => i.value)) === 'Fault_Stop' && (await page.$eval('#tt', s => s.value)) === 'BOOL');
  await page.fill('#td', 'Fault stop');
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(200);
  check('the tag is created in the program scope', await ev(() => MTPS.App.state.p.tasks[0].programs[0].tags.some(t => t.name === 'Fault_Stop' && t.type === 'BOOL')));
  check('back in the operand editor with the operand kept', (await page.$eval('#layer [data-op="0"]', i => i.value)) === 'Fault_Stop');
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(150);
  check('OK writes the operand into the rung', (await rungTexts())[1] === 'XIC(Motor_Run)XIO(Fault_Stop)OTE(Motor_Cmd);');
  check('the description shows above the instruction', (await page.$eval('#ladwrap svg', s => s.textContent)).includes('Fault stop'));
  await page.keyboard.press('Control+z');
  await page.waitForTimeout(100);
  check('Ctrl+Z undoes the operand', (await rungTexts())[1] === 'XIC(Motor_Run)XIO(?)OTE(Motor_Cmd);');
  await page.keyboard.press('Control+y');
  await page.waitForTimeout(100);
  check('Ctrl+Y redoes it', (await rungTexts())[1] === 'XIC(Motor_Run)XIO(Fault_Stop)OTE(Motor_Cmd);');
  await ev(() => MTPS.App.select({ ri: 1, path: [1] }));
  await page.click('.gbtn[data-mn="BR"]');
  await page.waitForTimeout(100);
  check('Branch puts a branch around the selected instruction', (await rungTexts())[1] === 'XIC(Motor_Run)[XIO(Fault_Stop),]OTE(Motor_Cmd);');
  await page.keyboard.press('Control+z');
  await page.keyboard.press('Delete');
  await page.waitForTimeout(100);
  check('Delete removes the selected instruction', (await rungTexts())[1] === 'XIC(Motor_Run)OTE(Motor_Cmd);');
  await page.keyboard.press('Control+r');
  await page.waitForTimeout(100);
  check('Ctrl+R adds an empty rung after the selection', (await rungTexts()).length === 6 && (await rungTexts())[2] === '');
  check('an empty rung is a verify error (⊗)', (await page.$$eval('#ladwrap text.err', t => t.length)) === 1);
  await page.keyboard.type('o');
  await page.waitForTimeout(100);
  check('typing with a rung selected opens quick entry', (await page.$eval('#pq', i => i.value)) === 'O');
  await page.fill('#pq', 'OTL Latch_X');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(150);
  check('quick entry adds the instruction with its operand', (await rungTexts())[2] === 'OTL(Latch_X);');
  check('Latch_X is undefined: the Errors pane says so', (await page.$eval('.derr .log', e => e.textContent)).includes("Error: Rung 2, OTL, Operand 0: Undefined tag 'Latch_X'."));
  await ev(() => MTPS.App.run('undo'));
  await ev(() => MTPS.App.run('undo'));
  await page.waitForTimeout(100);
  check('two undos remove the rung again', (await rungTexts()).length === 5);
  await page.click('#ladwrap rect.tap[data-rn][data-ri="1"]', { clickCount: 2 });
  await page.waitForTimeout(150);
  check('double-click on the rung number edits the rung as text', (await page.$eval('#rtx', t => t.value)) === 'XIC(Motor_Run)OTE(Motor_Cmd);');
  await page.fill('#rtx', 'XIC(Motor_Run)XIC(OL_OK)OTE(Motor_Cmd);');
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(100);
  check('the rung text is written back', (await rungTexts())[1] === 'XIC(Motor_Run)XIC(OL_OK)OTE(Motor_Cmd);');
  await page.click('#ladwrap rect.tap[data-ri="1"][data-p="1"]', { button: 'right' });
  await page.waitForTimeout(100);
  const menu = await page.$$eval('#layer .menu .it', a => a.map(x => [x.textContent.trim(), x.classList.contains('dis')]));
  check('right-click menu has the instruction items', menu.some(([t]) => t.startsWith('Cut')) && menu.some(([t]) => t.startsWith('Toggle Bit')));
  check('Toggle Bit is greyed out offline', menu.find(([t]) => t.startsWith('Toggle Bit'))[1] === true);
  await page.keyboard.press('Escape');

  console.log('Online, I/O panel, forces');
  await ev(() => MTPS.App.run('online'));
  await page.waitForTimeout(100);
  check('Go Online with an empty controller opens Download', (await page.$eval('#layer .dlg .dh b', b => b.textContent)) === 'Download');
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(150);
  check('after the download: "Return the controller to Remote Run?"', (await page.$eval('#layer .dlg', d => d.textContent)).includes('Return the controller to Remote Run?'));
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(150);
  check('online in Rem Run: mode box and green rails', (await page.$eval('[data-box="mode"]', b => b.textContent.trim())) === 'Rem Run' && (await page.$('#ladwrap svg.lad.run')) !== null);
  check('editing is locked online', (await page.$eval('.gbtn[data-mn="XIC"]', b => b.disabled)) === true);
  check('going online shows the I/O panel', (await page.$('#iob')) !== null);
  await page.waitForTimeout(100);
  await page.click('[data-io="1:1"]');
  await page.click('[data-io="1:2"]');
  await page.click('[data-io="1:0"]');
  await page.waitForTimeout(150);
  await page.click('[data-io="1:0"]');
  await page.waitForTimeout(200);
  check('I/O panel: S1 starts the motor and the seal-in holds', await ev(() => MTPS.App.ctl.read('Motor_Run') === 1));
  check('the output lamp of KM1 is on', (await page.$eval('.pt b.lamp', b => b.classList.contains('on'))) === true);
  check('true instructions get green bars', (await page.$$eval('#ladwrap rect.bar', r => r.length)) > 4);
  // clicking instructions while the ladder is redrawn by the running timer
  const pick = async (ri, p) => { for (let k = 0; k < 5; k++) { try { const r = await page.$(`#ladwrap rect.tap[data-ri="${ri}"][data-p="${p}"]`); const bb = await r.boundingBox(); await page.mouse.click(bb.x + bb.width / 2, bb.y + bb.height / 2); return; } catch (e) { await page.waitForTimeout(30); } } };
  await pick(2, '0');
  await page.waitForTimeout(80);
  await pick(3, '0');
  await page.waitForTimeout(80);
  check('online, with a timer running: another instruction can be selected', (await S()).sel && (await S()).sel.ri === 3);
  await ev(() => MTPS.App.select({ ri: 0, path: [0, 0, 0] }));
  const s0 = await ev(() => MTPS.App.state.io[1] || 0);
  await page.keyboard.press('Control+t');
  await page.waitForTimeout(100);
  check('Toggle Bit on an input switches its point on the I/O panel', (await ev(() => MTPS.App.state.io[1] || 0)) === (s0 ^ 1));
  await page.keyboard.press('Control+t');
  await page.waitForTimeout(50);
  await ev(() => MTPS.App.select({ ri: 0, path: [1] }));
  await page.keyboard.press('Control+t');
  await page.waitForTimeout(100);
  check('Ctrl+T on S0 STOP switches its field point off: the motor stops', await ev(() => MTPS.App.ctl.read('Stop_PB') === 0 && MTPS.App.ctl.read('Motor_Run') === 0));
  await ev(() => MTPS.App.run('fon'));
  await ev(() => MTPS.App.run('fen'));
  await page.click('[data-io="1:1"]');
  await page.waitForTimeout(200);
  check('a forced input holds against the I/O panel', await ev(() => MTPS.App.ctl.read('Stop_PB') === 1 && MTPS.App.ctl.forceState() === 'enabled'));
  check('the force marker ▸ON is drawn', (await page.$eval('#ladwrap svg', s => s.textContent)).includes('▸ON'));
  await ev(() => MTPS.App.run('fall'));
  await page.click('[data-pull="1"]');
  await page.waitForTimeout(150);
  check('Fault on the I/O panel: I/O LED "I/O Not Responding" and ⚠ on the module', (await page.$eval('#olbar', e => e.textContent)).includes('I/O Not Responding') && (await page.$eval('.nd[data-org="mod:1"]', e => e.textContent)).includes('⚠'));
  await page.click('.nd[data-org="mod:1"]');
  await page.waitForTimeout(100);
  check('Module Properties opens on Status with the fault code', (await page.$eval('#layer [data-pane="st"]', e => !e.hidden && e.textContent.includes('16#0204'))));
  await page.click('#layer #mp-x');
  await page.waitForTimeout(100);
  check('Put the card back: Running again', (await page.$eval('#layer [data-pane="st"]', e => e.textContent)).includes('Running'));
  await page.keyboard.press('Escape');
  await page.click('.nd[data-org="ctl"]');
  await page.waitForTimeout(100);
  check('Controller Properties: General, Major Faults, Minor Faults', (await page.$$eval('#layer [data-dt]', t => t.map(x => x.textContent.trim()).join('|'))).startsWith('General|Major Faults|Minor Faults'));
  await page.keyboard.press('Escape');
  await ev(() => MTPS.App.run('offline'));
  await ev(() => { const p = MTPS.App.state.p; p.tasks[0].programs[0].routines[0].rungs.push({ t: 'NOP();' }); MTPS.App.openProject(p, true); });
  await ev(() => MTPS.App.run('online'));
  await page.waitForTimeout(100);
  check('Go Online with another version in the controller: Upload or Download', (await page.$eval('#layer .dlg .dh b', b => b.textContent)) === 'Connected To Go Online');
  await page.evaluate(() => [...document.querySelectorAll('#layer .btn')].find(x => x.textContent.trim() === 'Upload…').click());
  await page.waitForTimeout(100);
  await page.click('#layer .btn.pri');
  await page.waitForTimeout(150);
  check('Upload opens the controller copy and goes online', (await rungTexts()).length === 5 && (await S()).online);
  await ev(() => MTPS.App.run('offline'));
  await page.waitForTimeout(100);
  check('Go Offline unlocks editing', (await page.$eval('.gbtn[data-mn="XIC"]', b => b.disabled)) === false);

  console.log('Projects');
  await page.reload();
  await page.waitForTimeout(300);
  check('the project is saved and reopens after a restart', (await rungTexts())[1] === 'XIC(Motor_Run)XIC(OL_OK)OTE(Motor_Cmd);');
  await ev(() => MTPS.App.openProject(MTPS.App.blank('Test_Line')));
  await page.waitForTimeout(100);
  check('a new project opens with one empty rung and the default rack', (await rungTexts()).length === 1 && (await ev(() => MTPS.App.state.p.rack.modules.length)) === 2);
  check('the window title follows the project', (await ev(() => document.title)).startsWith('MT PLC Studio - Test_Line'));
  check('no JS errors', errors.length === 0, errors.join(' | '));

  await browser.close();
  console.log(`\n${passed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
})();
